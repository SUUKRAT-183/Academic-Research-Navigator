"""
Build the controlled vocabulary (the list of "concepts") from a catalogue file.

Counts how often every subject/keyword value appears, throws away junk and
very rare values, and writes data/vocabulary.json, which backend/concepts.py
loads automatically.

    python -m scripts.build_vocabulary                      # uses data/catalogue.json
    python -m scripts.build_vocabulary --min-freq 3 --max-terms 500
"""
import argparse
import json
import os
import re
from collections import Counter

ROOT = os.path.join(os.path.dirname(__file__), "..")
JUNK = {"", "unknown", "n/a", "na", "none", "null", "nil", "-", "--", "general", "miscellaneous"}


def clean_term(term: str) -> str:
    """Library subject headings look like "Java (Computer program language) -- Handbooks".
    People search for "java", so keep only the main heading and drop the (qualifier) and subdivisions."""
    t = re.sub(r"\s+", " ", str(term).strip().lower())
    t = re.split(r"\s*--\s*|\s+-\s+", t)[0]        # main heading, without subdivisions ("--" or " - ")
    t = re.sub(r"\s*\([^)]*\)", "", t)              # drop "(qualifier)" parts
    return t.strip(" .,;:/-")


def build_vocabulary(catalogue_path, out_path, min_freq=None, max_terms=400, use_keywords=True):
    """min_freq=None means automatic: use 5, but drop to 3 or 2 if that would leave
    fewer than 20 concepts (small catalogues / sparse subjects). Never below 2,
    because a concept used by one record can't relate it to anything."""
    with open(catalogue_path, "r", encoding="utf-8") as f:
        resources = json.load(f)["resources"]

    counts = Counter()
    for r in resources:
        values = list(r.get("subjects", []))
        if use_keywords:
            values += list(r.get("keywords", []))
        # count each term once per record, so one record cannot inflate it
        for t in {clean_term(v) for v in values}:
            if t and t not in JUNK and len(t) >= 3:
                counts[t] += 1

    candidates = [min_freq] if min_freq else [5, 3, 2]
    for threshold in candidates:
        terms = [t for t, c in counts.most_common() if c >= threshold][:max_terms]
        if len(terms) >= 20:
            break
    build_vocabulary.last_threshold = threshold
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump({"_note": "Generated by scripts/build_vocabulary.py. Add hand-written "
                            "synonyms under \"aliases\", e.g. {\"ml\": \"machine learning\"}.",
                   "terms": sorted(terms), "aliases": {}}, f, indent=2, ensure_ascii=False)
    return len(resources), len(counts), terms


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--catalogue", default=os.path.join(ROOT, "data", "catalogue.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "data", "vocabulary.json"))
    ap.add_argument("--min-freq", type=int, default=None,
                    help="ignore subjects used by fewer records than this (default: automatic, 5 -> 3 -> 2)")
    ap.add_argument("--max-terms", type=int, default=400)
    ap.add_argument("--subjects-only", action="store_true", help="ignore the keywords field")
    a = ap.parse_args()

    n, distinct, terms = build_vocabulary(a.catalogue, a.out, a.min_freq, a.max_terms,
                                          use_keywords=not a.subjects_only)
    print(f"{n} records, {distinct} distinct subject values, {len(terms)} kept as concepts "
          f"(used by at least {build_vocabulary.last_threshold} records) -> {a.out}")
    print("Top concepts:", ", ".join(terms[:15]))
    if len(terms) < 20:
        print("WARNING: fewer than 20 concepts. Concept chips and 'related concepts' will be thin. "
              "Try --min-freq 2, or check that the subjects column was mapped correctly.")


if __name__ == "__main__":
    main()
